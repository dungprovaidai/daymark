import Foundation

struct WidgetSectionInfo: Codable, Equatable, Hashable, Identifiable {
    let id: UUID
    let title: String
}

struct WidgetJournalInfo: Codable, Equatable, Hashable, Identifiable {
    let id: UUID
    let title: String
    let icon: String
    let color: String
    let sections: [WidgetSectionInfo]
}

struct WidgetJournalProgress: Codable, Equatable, Identifiable {
    let journalID: UUID
    let done: Int
    let total: Int
    let note: String
    var id: UUID { journalID }
    var fraction: Double { total > 0 ? min(1, max(0, Double(done) / Double(total))) : 0 }
}

struct WidgetEventInfo: Codable, Equatable, Identifiable {
    let id: String
    let eventID: UUID
    let title: String
    let start: Date
    let end: Date
    let allDay: Bool
    let timeZoneID: String
    let color: String
    let icon: String
    let location: String
    let isRecurring: Bool
    let completed: Bool
    let journalEntryID: UUID?
}

struct WidgetReminderInfo: Codable, Equatable, Identifiable {
    let id: String
    let eventID: UUID
    let title: String
    let body: String
    let fireDate: Date
    let eventStart: Date
}

struct WidgetChecklistItem: Codable, Equatable, Identifiable {
    let fieldID: UUID
    let journalID: UUID
    let title: String
    let icon: String
    let sectionID: UUID?
    let sectionTitle: String?
    var checked: Bool
    var id: UUID { fieldID }
}

/// A read-only snapshot generated by the app. The widget extension never opens
/// the SwiftData store; it only reads this file from the App Group container.
struct WidgetSnapshot: Codable, Equatable {
    var generatedAt: Date
    var displayName: String
    var todayDayKey: String
    var journals: [WidgetJournalInfo]
    var defaultJournalID: UUID?
    var progress: [WidgetJournalProgress]
    var nextEvent: WidgetEventInfo?
    var upcoming: [WidgetEventInfo]
    var reminders: [WidgetReminderInfo]
    var checklist: [WidgetChecklistItem]
    var notificationsEnabled: Bool

    static let empty = WidgetSnapshot(
        generatedAt: .distantPast,
        displayName: "",
        todayDayKey: "",
        journals: [],
        defaultJournalID: nil,
        progress: [],
        nextEvent: nil,
        upcoming: [],
        reminders: [],
        checklist: [],
        notificationsEnabled: false
    )

    var defaultJournal: WidgetJournalInfo? {
        journals.first { $0.id == defaultJournalID } ?? journals.first
    }

    func journal(id: UUID?) -> WidgetJournalInfo? {
        journals.first { $0.id == id } ?? defaultJournal
    }

    func progressForJournal(_ journalID: UUID) -> WidgetJournalProgress? {
        progress.first { $0.journalID == journalID }
    }

    func checklistItems(journalID: UUID?, sectionID: UUID?) -> [WidgetChecklistItem] {
        let selectedJournal = journal(id: journalID)
        return checklist.filter { item in
            guard item.journalID == selectedJournal?.id else { return false }
            guard let sectionID else { return true }
            return item.sectionID == sectionID
        }
    }
}

enum WidgetSnapshotStore {
    private static var encoder: JSONEncoder {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        encoder.outputFormatting = [.sortedKeys]
        return encoder
    }

    private static var decoder: JSONDecoder {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return decoder
    }

    static func read() -> WidgetSnapshot? {
        WidgetFileLock.withLock { readUnlocked() }
    }

    static func write(_ snapshot: WidgetSnapshot) {
        WidgetFileLock.withLock { writeUnlocked(snapshot) }
    }

    /// Used by interactive widget intents to update the displayed state
    /// immediately while the durable change waits for the app to consume it.
    static func update(_ change: (inout WidgetSnapshot) -> Void) {
        WidgetFileLock.withLock {
            guard var snapshot = readUnlocked() else { return }
            change(&snapshot)
            writeUnlocked(snapshot)
        }
    }

    private static func readUnlocked() -> WidgetSnapshot? {
        guard let data = try? Data(contentsOf: DaymarkShared.snapshotURL) else { return nil }
        return try? decoder.decode(WidgetSnapshot.self, from: data)
    }

    private static func writeUnlocked(_ snapshot: WidgetSnapshot) {
        DaymarkShared.ensureDirectory()
        guard let data = try? encoder.encode(snapshot) else { return }
        try? data.write(to: DaymarkShared.snapshotURL, options: .atomic)
    }
}
